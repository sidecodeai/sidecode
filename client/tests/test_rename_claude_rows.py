def test_every_other_row_is_activity_as_it_always_was(order: list[dict[str, Any]]) -> None:
    assert names_only(order) == [False]


def test_an_answer_after_other_work_is_not_taken_for_a_renames() -> None:
    assert names_only([COMMAND, WORDS], [STDOUT]) == [False, False]
    assert names_only([COMMAND], [WORDS], [STDOUT, NOTE]) == [True, False, False]
