"""A55: the rows that name a Claude Code session, written, read back and told apart."""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import pytest

from rc_client.agents.claude import markers, name_rows, transcripts
from rc_client.sessions.typist import typeable

SESSION = "5f8f6a02-1c9d-4a1e-9d4a-2f1e4c7b90aa"
LEDGER = "Ledger migration"


def user_row(text: str, *, meta: bool = False, uuid: str = "u1") -> dict[str, Any]:
    row: dict[str, Any] = {
        "type": "user",
        "uuid": uuid,
        "message": {"role": "user", "content": text},
    }
    if meta:
        row["isMeta"] = True
    return row


def transcript(tmp_path: Path, rows: list[dict[str, Any]] | None = None) -> Path:
    path = tmp_path / f"{SESSION}.jsonl"
    body = "".join(json.dumps(row) + "\n" for row in rows or [user_row("hello")])
    path.write_text(body, encoding="utf-8")
    return path


def lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines()


def command_row(name: str, args: str = "") -> dict[str, Any]:
    """The row of a typed slash command, as the CLI files it."""
    text = f"<command-name>{name}</command-name>\n<command-args>{args}</command-args>"
    return user_row(text, uuid="cx")


# What the CLI files for a typed `/rename Ledger migration`, row by row.
COMMAND = user_row(
    "<command-name>/rename</command-name>\n<command-message>rename</command-message>\n"
    f"<command-args>{LEDGER}</command-args>",
    uuid="c1",
)
STDOUT = user_row(f"<local-command-stdout>Session renamed to: {LEDGER}</local-command-stdout>")
NOTE = user_row(
    f'The user named this session "{LEDGER}". This may indicate the session\'s focus or intent.',
    meta=True,
    uuid="m1",
)
CUSTOM_TITLE = {"type": "custom-title", "customTitle": LEDGER, "sessionId": SESSION}
AGENT_NAME = {"type": "agent-name", "agentName": LEDGER, "sessionId": SESSION}
# What the CLI files before a command it prints for, as an instruction to the model.
CAVEAT = user_row(
    "<local-command-caveat>Caveat: The messages below were generated by the user while running "
    "local commands. DO NOT respond to these messages.</local-command-caveat>",
    meta=True,
    uuid="cv1",
)
WORDS = user_row("carry on", uuid="w1")


# ------------------------------------------------------------------ writing the rows


def test_both_rows_are_written_as_the_cli_writes_them(tmp_path: Path) -> None:
    path = transcript(tmp_path)

    name_rows.append_names(path, SESSION, LEDGER, held=False)

    written = lines(path)[1:]
    assert written == [
        json.dumps(CUSTOM_TITLE, separators=(",", ":")),
        json.dumps(AGENT_NAME, separators=(",", ":")),
    ]
    assert path.read_bytes().endswith(b"\n")


def test_a_session_a_cli_holds_gets_the_title_row_alone(tmp_path: Path) -> None:
    """The CLI re-stamps its cached `agent-name`, so one written under it would be lost."""
    path = transcript(tmp_path)

    name_rows.append_names(path, SESSION, LEDGER, held=True)

    assert [json.loads(line)["type"] for line in lines(path)[1:]] == ["custom-title"]


def test_a_line_a_live_cli_may_be_writing_is_left_as_it_is(tmp_path: Path) -> None:
    """The tail of a transcript a CLI holds is the CLI's: no newline of ours goes into it."""
    path = transcript(tmp_path)
    with path.open("ab") as handle:
        handle.write(b'{"type":"user","uuid":"in-flight","mess')
    before = path.read_bytes()

    name_rows.append_names(path, SESSION, LEDGER, held=True)

    written = path.read_bytes()[len(before) :]
    assert written == (json.dumps(CUSTOM_TITLE, separators=(",", ":")) + "\n").encode()
    assert b"\n\n" not in path.read_bytes()


def test_a_transcript_cut_short_is_sealed_before_the_rows(tmp_path: Path) -> None:
    path = transcript(tmp_path)
    with path.open("ab") as handle:
        handle.write(b'{"type":"user","uuid":"torn","mess')

    name_rows.append_names(path, SESSION, LEDGER, held=False)

    tail = transcripts.TitleTail(path=str(path))
    assert tail.read_new() == [transcripts.Title(LEDGER, by_user=True)]
    # The cut row stays cut, on a line of its own, and nothing it said is lost to ours.
    assert lines(path)[1].startswith('{"type":"user","uuid":"torn"')
    assert json.loads(lines(path)[2]) == CUSTOM_TITLE


def test_names_that_are_not_ascii_are_read_back_as_they_were(tmp_path: Path) -> None:
    path = transcript(tmp_path)
    mark = name_rows.size_of(path)
    name = "修复令牌 \U0001f642"

    name_rows.append_names(path, SESSION, name, held=False)

    assert name_rows.name_since(path, mark) == name


def test_a_transcript_that_is_not_there_is_never_created(tmp_path: Path) -> None:
    path = tmp_path / f"{SESSION}.jsonl"

    with pytest.raises(FileNotFoundError):
        name_rows.append_names(path, SESSION, LEDGER, held=False)

    assert not path.exists()


def test_an_empty_transcript_is_a_stub_and_not_a_session(tmp_path: Path) -> None:
    path = tmp_path / f"{SESSION}.jsonl"
    path.write_bytes(b"")

    with pytest.raises(FileNotFoundError):
        name_rows.append_names(path, SESSION, LEDGER, held=False)

    assert path.read_bytes() == b""


@pytest.mark.skipif(os.geteuid() == 0, reason="root can write a file it has no permission to")
def test_a_transcript_that_cannot_be_written_raises_the_os_error(tmp_path: Path) -> None:
    path = transcript(tmp_path)
    path.chmod(0o444)

    with pytest.raises(PermissionError):
        name_rows.append_names(path, SESSION, LEDGER, held=False)


def test_the_file_is_opened_for_append_and_never_for_creation_and_written_once(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    path = transcript(tmp_path)
    flags: list[int] = []
    writes: list[int] = []
    real_open, real_write = os.open, os.write

    def spy_open(target: Any, mode: int, *args: Any, **kwargs: Any) -> int:
        flags.append(mode)
        return real_open(target, mode, *args, **kwargs)

    def spy_write(descriptor: int, data: Any) -> int:
        writes.append(len(data))
        return real_write(descriptor, data)

    monkeypatch.setattr(os, "open", spy_open)
    monkeypatch.setattr(os, "write", spy_write)

    name_rows.append_names(path, SESSION, LEDGER, held=False)

    assert len(flags) == 1
    assert flags[0] & os.O_APPEND and not flags[0] & os.O_CREAT
    assert len(writes) == 1, "both rows go in one write, so nothing lands between them"


# ------------------------------------------------------------------ reading them back


def test_the_name_the_cli_wrote_last_since_the_mark_is_the_answer(tmp_path: Path) -> None:
    older = {"type": "custom-title", "customTitle": "Before the request", "sessionId": SESSION}
    path = transcript(tmp_path, [user_row("hello"), older])
    mark = name_rows.size_of(path)
    assert name_rows.name_since(path, mark) is None

    with path.open("a", encoding="utf-8") as handle:
        for row in (
            {"type": "ai-title", "aiTitle": "A generated one", "sessionId": SESSION},
            {"type": "custom-title", "customTitle": LEDGER, "sessionId": SESSION},
            {"type": "custom-title", "customTitle": f"{LEDGER} (2)", "sessionId": SESSION},
        ):
            handle.write(json.dumps(row) + "\n")

    assert name_rows.name_since(path, mark) == f"{LEDGER} (2)"
    assert name_rows.name_since(path, 0) == f"{LEDGER} (2)"


def test_a_transcript_that_is_gone_is_zero_long(tmp_path: Path) -> None:
    assert name_rows.size_of(tmp_path / "gone.jsonl") == 0


